"""Writes js/globe-data.js for the globe in the footer.

Outlines come from world-atlas's countries-110m.json (ISC license), a
TopoJSON redistribution of Natural Earth's 1:110m admin-0 countries; label
points, and the two-letter codes visitors are counted by, come from
Natural Earth's 1:50m admin-0 countries. Natural Earth is in the public
domain.
https://github.com/topojson/world-atlas
https://github.com/nvkelso/natural-earth-vector/tree/master/geojson

    python3 tools/globe-data.py countries-110m.json \\
        ne_50m_admin_0_countries.geojson > js/globe-data.js

As in TopoJSON, each border is stored once, as an arc, and each country as
rings of arc numbers (~n for arc n reversed), so shared borders are drawn
once. Arcs are points in tenths of a degree: the first as two int16s, then
each step as two int8s, or as -128 and two int16s when it is too long.
Arcs are simplified to 0.2 degrees, which keeps their ends, so borders
still meet.
"""

import base64
import json
import struct
import sys

from shapely.geometry import LineString

topo = json.load(open(sys.argv[1]))
(kx, ky), (tx, ty) = topo["transform"]["scale"], topo["transform"]["translate"]

out = bytearray(struct.pack("<H", len(topo["arcs"])))
for arc in topo["arcs"]:
    x = y = 0
    points = []
    for dx, dy in arc:
        x += dx
        y += dy
        points.append((x * kx + tx, y * ky + ty))
    if len(points) > 2:
        points = list(LineString(points).simplify(0.2).coords)
    points = [(round(x * 10), round(y * 10)) for x, y in points]
    out += struct.pack("<Hhh", len(points), *points[0])
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        dx, dy = x1 - x0, y1 - y0
        if -127 <= dx <= 127 and -127 <= dy <= 127:
            out += struct.pack("<bb", dx, dy)
        else:
            out += struct.pack("<bhh", -128, dx, dy)

# Numeric ISO codes, as world-atlas uses, to the two-letter ones.
alpha2 = {}
labels = []
for f in json.load(open(sys.argv[2]))["features"]:
    p = f["properties"]
    code = next((c for c in (p.get("ISO_A2_EH"), p.get("ISO_A2")) if c and len(c) == 2 and c != "-99"), None)
    if not code:
        continue
    for n in (p.get("ISO_N3_EH"), p.get("ISO_N3")):
        if n and n != "-99":
            alpha2.setdefault(n.zfill(3), code)
    if code not in [c for c, _, _ in labels]:
        labels.append((code, p["LABEL_Y"], p["LABEL_X"]))

countries = topo["objects"]["countries"]["geometries"]
out += struct.pack("<H", len(countries))
codes = []
for g in countries:
    codes.append(alpha2.get(g.get("id", ""), ""))
    polygons = [g["arcs"]] if g["type"] == "Polygon" else g["arcs"]
    rings = [ring for polygon in polygons for ring in polygon]
    out += struct.pack("<B", len(rings))
    for ring in rings:
        out += struct.pack(f"<H{len(ring)}h", len(ring), *ring)

print("// Generated by tools/globe-data.py from world-atlas and Natural Earth.")
print(f'export const CODES = "{",".join(codes)}";')
print(f'export const SHAPES = "{base64.b64encode(out).decode()}";')
print(f'export const LABELS = "{"|".join(f"{c},{lat:.1f},{lon:.1f}" for c, lat, lon in labels)}";')
missing = [g["properties"]["name"] for g, c in zip(countries, codes) if not c]
print(f"// {len(topo['arcs'])} arcs, {len(countries)} countries, {len(out)} bytes; no code: {missing}", file=sys.stderr)
